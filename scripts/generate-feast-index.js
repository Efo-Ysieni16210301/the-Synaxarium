// Scans src/data/feasts/*.json and (re)writes index.ts so every file
// there is automatically registered - no manual import line needed.
// Runs automatically before `npm run dev` and `npm run build` (see the
// "predev"/"prebuild" scripts in package.json), so adding a new day's
// JSON file and just committing/pushing is enough.

const fs = require("fs");
const path = require("path");

const feastsDir = path.join(__dirname, "..", "src", "data", "feasts");
const outputFile = path.join(feastsDir, "index.ts");

const files = fs
  .readdirSync(feastsDir)
  .filter((f) => /^\d+-\d+\.json$/.test(f)) // only "<month>-<day>.json"
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

if (files.length === 0) {
  console.warn(
    "No feast JSON files found in src/data/feasts/ - index.ts not regenerated.",
  );
  process.exit(0);
}

const importLines = [];
const registryLines = [];

for (const file of files) {
  const key = file.replace(/\.json$/, ""); // e.g. "1-9"
  const varName = `feast_${key.replace("-", "_")}`; // e.g. feast_1_9
  importLines.push(`import ${varName} from './${file}';`);
  registryLines.push(`  '${key}': ${varName} as FeastDay,`);
}

const content = `// AUTO-GENERATED by scripts/generate-feast-index.js - do not edit by hand.
// It is regenerated automatically before every \`npm run dev\` / \`npm run build\`.
// To add a day: just add its JSON file under src/data/feasts/ and rerun
// either command (or push - Vercel runs \`npm run build\` too).

import type { FeastDay, FeastKey } from '@/types/feast';
${importLines.join("\n")}

const registry: Record<FeastKey, FeastDay> = {
${registryLines.join("\n")}
};

export function getFeastByKey(key: FeastKey): FeastDay | undefined {
  return registry[key];
}

export function getAllFeastKeys(): FeastKey[] {
  return Object.keys(registry) as FeastKey[];
}

export function getAllFeasts(): FeastDay[] {
  return Object.values(registry);
}
`;

fs.writeFileSync(outputFile, content);
console.log(
  `Generated src/data/feasts/index.ts with ${files.length} feast day(s).`,
);
